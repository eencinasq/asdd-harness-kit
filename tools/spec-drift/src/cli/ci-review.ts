/**
 * CI mode (spec-drift-demand REQ-004, ADR-004): a GitHub Actions workflow that reviews a pull request with Claude Code
 * and this server, and leaves a PENDING review. A pending review belongs to the token that created it, so `gh` runs with
 * a reviewer's token secret: that reviewer sees the draft on the PR and submits it (or not). Printed, never written.
 */

export const REVIEWER_SECRET = 'SPEC_DRIFT_REVIEWER_TOKEN';
export const API_KEY_SECRET = 'ANTHROPIC_API_KEY';

/** The review tools the CI agent may call: no dashboard-only tool, nothing that submits. */
export const CI_REVIEW_TOOLS = [
	'pr_review_start',
	'pr_review_next_group',
	'pr_review_submit_findings',
	'pr_review_read_file',
	'pr_review_search',
	'pr_review_verify_findings',
	'pr_review_submit_requirements',
	'pr_review_status',
	'pr_review_publish',
] as const;

export type CiReviewOptions = {
	/** owner/name of the asdd-harness-kit repository that holds the server. */
	readonly kitRepo: string;
	/** Branch, tag or commit of the kit (pin a commit in production). */
	readonly kitRef: string;
};

const KIT_DIR = '.spec-drift-kit';

export const reviewPrompt = (pr: string): string =>
	[
		`Review pull request #${pr} of this repository with the spec-drift MCP server.`,
		`1. Call pr_review_start with { "pr": ${pr} }.`,
		'2. For each group: pr_review_next_group, then pr_review_submit_findings (an empty list when the group is clean).',
		'3. When asked, verify the findings with pr_review_verify_findings, and the ticket criteria with pr_review_submit_requirements.',
		'4. Call pr_review_publish once coverage is complete. It creates a PENDING review only.',
		'Never approve, request changes or submit a review; a person submits the pending review on GitHub.',
	].join('\n');

export const ciReviewWorkflow = ({ kitRepo, kitRef }: CiReviewOptions): string => {
	const allowed = CI_REVIEW_TOOLS.map((t) => `mcp__spec-drift__${t}`).join(',');
	// biome-ignore lint/suspicious/noTemplateCurlyInString: a GitHub Actions expression, written as is into the workflow
	const pr = '${{ github.event.pull_request.number || inputs.pr }}';
	return `# spec-drift PR review in CI (generated by \`spec-drift ci-review\`).
# Leaves a PENDING review owned by the reviewer whose token is in ${REVIEWER_SECRET};
# that person submits it on GitHub. Nothing is approved or submitted by the workflow.
#
# Secrets:
#   ${API_KEY_SECRET}              Anthropic API key for Claude Code
#   ${REVIEWER_SECRET}  a reviewer's fine-grained token: Pull requests read/write, Contents read, Issues read
name: spec-drift review

on:
  pull_request:
    types: [opened, ready_for_review]
  workflow_dispatch:
    inputs:
      pr:
        description: Pull request number
        required: true

permissions:
  contents: read
  pull-requests: read

concurrency:
  group: spec-drift-review-${pr}
  cancel-in-progress: true

jobs:
  review:
    # Drafts are skipped; fork PRs get no secrets.
    if: >-
      github.event_name == 'workflow_dispatch' ||
      (github.event.pull_request.draft == false &&
       github.event.pull_request.head.repo.full_name == github.repository)
    runs-on: ubuntu-latest
    timeout-minutes: 30
    steps:
      - uses: actions/checkout@v4
        with:
          fetch-depth: 0
      - uses: actions/checkout@v4
        with:
          repository: ${kitRepo}
          ref: ${kitRef}
          path: ${KIT_DIR}
      - uses: actions/setup-node@v4
        with:
          node-version: 24
      - name: Build the spec-drift server
        working-directory: ${KIT_DIR}/tools/spec-drift
        run: corepack enable && pnpm install --frozen-lockfile && pnpm build
      - name: Install Semgrep (the repository's .semgrep/ rules)
        run: pipx install semgrep
      - name: Write the MCP config
        env:
          GH_TOKEN: \${{ secrets.${REVIEWER_SECRET} }}
        run: |
          node -e '
            const config = { mcpServers: { "spec-drift": {
              command: "node",
              args: [process.env.GITHUB_WORKSPACE + "/${KIT_DIR}/tools/spec-drift/bin/spec-drift.mjs"],
              env: {
                CI: "true",
                GH_TOKEN: process.env.GH_TOKEN,
                PR_REVIEW_REPO: process.env.GITHUB_WORKSPACE,
                PR_REVIEW_ROOT: process.env.RUNNER_TEMP + "/pr-review",
                SPEC_DRIFT_TOOLSETS: "review",
                PATH: process.env.PATH
              }
            } } };
            require("fs").writeFileSync(process.env.RUNNER_TEMP + "/spec-drift-mcp.json", JSON.stringify(config));
          '
      - uses: anthropics/claude-code-action@v1
        with:
          anthropic_api_key: \${{ secrets.${API_KEY_SECRET} }}
          claude_args: |
            --mcp-config \${{ runner.temp }}/spec-drift-mcp.json
            --allowedTools ${allowed}
            --max-turns 80
          prompt: |
${reviewPrompt(pr)
	.split('\n')
	.map((l) => `            ${l}`)
	.join('\n')}
`;
};
