#!/usr/bin/env node
/**
 * init-slice.mjs — scaffold a new slice with v3.0 append-only session structure.
 *
 * Lite-first: slices start in lite mode by default. Pass --full only for work
 * known upfront to be cross-cutting/architectural. Pass --hotfix for a ≤1-file
 * bugfix (starts at implementation with one stub feature; no Discovery theatre).
 *
 * --source-json '<object>' adds a `source` block (tracker provenance; asdd intake, external-trackers) to the 001 session.
 *
 * Usage: asdd slice init <slice-id> [--full | --hotfix] [--source-json '<json object>']
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

const root = process.cwd();
const args = process.argv.slice(2);
const sourceAt = args.indexOf('--source-json');
const sourceJson = sourceAt >= 0 ? args[sourceAt + 1] : undefined;
const sliceId = args.find((a, i) => !a.startsWith('-') && !(sourceAt >= 0 && i === sourceAt + 1));
const fullMode = args.includes('--full');
const hotfixMode = args.includes('--hotfix');

let source;
if (sourceAt >= 0) {
  try {
    source = JSON.parse(sourceJson ?? '');
  } catch {
    source = undefined;
  }
  if (!source || typeof source !== 'object' || Array.isArray(source)) {
    console.error('FAIL  --source-json must be a JSON object');
    process.exit(1);
  }
}

if (!sliceId || sliceId.startsWith('-')) {
  console.error("Usage: asdd slice init <slice-id> [--full | --hotfix] [--source-json '<json object>']");
  process.exit(1);
}

if (fullMode && hotfixMode) {
  console.error('FAIL  --full and --hotfix are mutually exclusive');
  process.exit(1);
}

if (!/^[a-z0-9_-]+$/.test(sliceId)) {
  console.error('FAIL  slice-id must be lowercase alphanumeric with hyphens/underscores');
  process.exit(1);
}

const mode = hotfixMode ? 'hotfix' : fullMode ? 'full' : 'lite';

// Duplicate check against the generated index AND the sessions tree (registry.json is regenerated by sync;
// global state/manifest.json retired — RV1-AR-1).
const stateDir = join(root, '.harness/state');
if (!existsSync(stateDir)) {
  console.error('FAIL  .harness/state not found — run: asdd repair (or asdd install .)');
  process.exit(1);
}
const registryPath = join(stateDir, 'registry.json');
const registrySlices = existsSync(registryPath)
  ? (JSON.parse(readFileSync(registryPath, 'utf8')).slices ?? [])
  : [];
if (
  registrySlices.some((s) => (typeof s === 'string' ? s : s?.slice_id) === sliceId) ||
  existsSync(join(stateDir, 'slices', sliceId))
) {
  console.error(`FAIL  slice "${sliceId}" already exists (registry.json or state/slices/)`);
  process.exit(1);
}

const nowIso = new Date().toISOString();

// Paths
const sliceDir = join(root, '.harness/state/slices', sliceId);
const sessionsDir = join(sliceDir, 'sessions');
const specDir = join(root, '.harness/specs', sliceId);
const featuresPath = join(root, '.harness/features', `${sliceId}.features.json`);

// 1. Create session directory and initial session
mkdirSync(sessionsDir, { recursive: true });
const initialSession = {
  schema_version: '1.0',
  session_id: `sess-${sliceId}-001`,
  timestamp: nowIso,
  agent: 'human',
  human: 'squad',
  slice_id: sliceId,
  event_type: 'phase_started',
  phase: hotfixMode ? 'implementation' : 'discovery',
  mode,
  evidence: hotfixMode
    ? 'Hotfix slice initialized (feature + evidence path; no Discovery theatre)'
    : 'Slice initialized',
  concerns: [],
  ...(source ? { source } : {}),
};
writeFileSync(join(sessionsDir, '001-initial.json'), `${JSON.stringify(initialSession, null, 2)}\n`);
console.log(`CREATE .harness/state/slices/${sliceId}/sessions/001-initial.json`);

// 2. Spec directory
mkdirSync(specDir, { recursive: true });
console.log(`DIR    .harness/specs/${sliceId}`);

// 3. Stub tasks.md (source_tasks target must exist for invariants)
const tasksStub = hotfixMode
  ? `# ${sliceId} — Hotfix\n\n> Single-file (or single-feature) fix. Fill TASK-001 scope_paths and verification.\n\n| Task | Notes |\n|------|-------|\n| TASK-001 Hotfix | Replace title/behavior/verification; keep one feature. |\n`
  : `# ${sliceId} — Tasks\n\n> Planned during Task Planning phase.\n\n`;
writeFileSync(join(specDir, 'tasks.md'), tasksStub);
console.log(`CREATE .harness/specs/${sliceId}/tasks.md`);

// 4. Features file
mkdirSync(join(root, '.harness/features'), { recursive: true });
const featuresDoc = {
  schema_version: '1.0',
  slice_id: sliceId,
  source_tasks: `.harness/specs/${sliceId}/tasks.md`,
  features: hotfixMode
    ? [
        {
          id: 'TASK-001',
          title: 'Hotfix',
          user_visible_behavior: 'Describe the observable fix; replace before marking passing.',
          status: 'not_started',
          priority: 1,
          owner: 'squad',
          req_ids: [],
          depends_on: [],
          verification: ['echo "replace with a real verification command"'],
          evidence: '',
          scope_paths: [`.harness/specs/${sliceId}/tasks.md`],
        },
      ]
    : [],
};
writeFileSync(featuresPath, `${JSON.stringify(featuresDoc, null, 2)}\n`);
console.log(`CREATE ${featuresPath.replace(`${root}/`, '')}`);

// 5. Generate v3.0 manifest from sessions (sync-state also regenerates the registry and PROGRESS.md)
const { spawnSync } = await import('node:child_process');
const syncResult = spawnSync(process.execPath, [decodeURIComponent(new URL('./sync-state.mjs', import.meta.url).pathname), '--slice', sliceId], {
  cwd: root,
  encoding: 'utf8',
});
if (syncResult.status !== 0) {
  console.error('WARN  sync-state failed:', syncResult.stderr);
} else {
  console.log(`SYNC   .harness/state/slices/${sliceId}/manifest.json`);
}

// 6. The generated index (registry.json) picks the slice up on the next `asdd sync` — no global manifest to update.

if (hotfixMode) {
  console.log(`\nSlice "${sliceId}" initialized as hotfix. Edit the stub feature in .harness/features/${sliceId}.features.json, then implement.`);
} else {
  console.log(`\nSlice "${sliceId}" initialized. Next: write .harness/specs/${sliceId}/intent.md`);
}
