// `asdd install <dir> --pr`: the install as a pull request. The branch starts from origin's default branch (never the
// local checkout, which may be behind), so the pull request holds only what the kit adds or changes. Preflight first,
// with every problem named; a failure before the commit puts the repository back as it was.
import { spawnSync } from 'node:child_process';
import { existsSync, realpathSync } from 'node:fs';
import { join, resolve } from 'node:path';

import { CliError } from '../paths.mjs';
import { info, log, ok } from '../ui.mjs';
import { INSTALLING_MARKER } from './index.mjs';
import { kitVersion } from './phases.mjs';

/** Paths compared after symlinks (macOS /var → /private/var). */
const real = (p) => {
  try {
    return realpathSync(p);
  } catch {
    return resolve(p);
  }
};

const firstLine = (s) => String(s ?? '').trim().split('\n')[0] ?? '';

/** The branch an install of `version` is proposed on. */
export const prBranch = (version) => `chore/asdd-harness-kit-${version}`;

/**
 * Pure: the facts gathered about the repository → the problems that block a --pr install, each with a message.
 * @param {{ isGitRepo: boolean, isTopLevel?: boolean, linkedWorktree?: boolean, clean?: boolean, remoteUrl?: string | null,
 *   defaultBranch?: string | null, ghAuthed?: boolean, branchTaken?: boolean, installing?: boolean, branch?: string }} f
 * @returns {{ code: string, message: string }[]}
 */
export function prPreflight(f) {
  if (!f.isGitRepo) return [{ code: 'not-git', message: 'The target is not a git repository: --pr needs one with an origin remote.' }];
  const problems = [];
  if (f.isTopLevel === false) problems.push({ code: 'not-root', message: 'The target is not the root of its git repository: pass the repository root.' });
  if (f.linkedWorktree) problems.push({ code: 'worktree', message: 'The target is a linked worktree: run --pr in the main checkout.' });
  if (f.installing) problems.push({ code: 'install-in-progress', message: `An earlier install was interrupted (${INSTALLING_MARKER}): finish it without --pr first.` });
  if (!f.clean) problems.push({ code: 'dirty', message: 'The working tree has uncommitted or untracked changes: commit or stash them, so the pull request holds only the kit.' });
  if (!f.remoteUrl) problems.push({ code: 'no-remote', message: 'There is no "origin" remote to push the branch to.' });
  else if (!f.defaultBranch) problems.push({ code: 'no-default-branch', message: 'The default branch of origin is unknown: run "git remote set-head origin --auto".' });
  if (!f.ghAuthed) problems.push({ code: 'gh-auth', message: 'The GitHub CLI is missing or not signed in: run "gh auth login".' });
  if (f.branchTaken) problems.push({ code: 'branch-exists', message: `The branch ${f.branch} already exists here or on origin: merge or close its pull request and delete the branch.` });
  return problems;
}

function prBody(result, base) {
  const { created, updated, kept, skipped } = result.files;
  return [
    result.previous ? `Upgrades asdd-harness-kit ${result.previous} → ${result.version}.` : `Installs asdd-harness-kit ${result.version}.`,
    '',
    `Generated by \`asdd install --pr\` from \`origin/${base}\`: ${created} created, ${updated} updated, ${kept} unchanged, ${skipped} skipped.`,
    ...(result.runtimes ? [`Runtimes: ${result.runtimes}.`] : []),
    ...(result.modules ? [`Modules: ${result.modules}.`] : []),
    ...(result.skipped.length
      ? ['', 'Kit files this project changed were left as they are (`asdd install --force` takes the kit version):', ...result.skipped.map((f) => `- \`${f}\``)]
      : []),
    '',
    '## After merging',
    '',
    '1. Pull the default branch.',
    '2. Fill the bindings that are still stubs (`.harness/steering/*.md`), then read `AGENTS.md`.',
    '3. Check the install with `npx asdd-harness-kit doctor`.',
    '',
  ].join('\n');
}

/** @returns {object} the install result plus `branch`, `base`, and the pull request `url` */
export function installWithPr(o, kit, runInstall) {
  const gh = process.env.ASDD_GH || 'gh';
  const target = o.target;
  const run = (cmd, args) => {
    const res = spawnSync(cmd, args, { cwd: target, encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 });
    return { code: res.error ? 1 : (res.status ?? 1), stdout: res.stdout ?? '', stderr: res.stderr || res.error?.message || '' };
  };
  const git = (...args) => run('git', args);
  const must = (res, what) => {
    if (res.code !== 0) throw new CliError(`${what} failed: ${firstLine(res.stderr) || firstLine(res.stdout) || `exit ${res.code}`}`);
    return res;
  };

  const version = kitVersion(kit);
  const branch = prBranch(version);
  const top = git('rev-parse', '--show-toplevel');
  const facts = { isGitRepo: top.code === 0, branch };
  if (facts.isGitRepo) {
    facts.isTopLevel = real(firstLine(top.stdout)) === real(target);
    const gitDir = firstLine(git('rev-parse', '--absolute-git-dir').stdout);
    const commonDir = firstLine(git('rev-parse', '--path-format=absolute', '--git-common-dir').stdout);
    facts.linkedWorktree = Boolean(gitDir && commonDir && real(gitDir) !== real(commonDir));
    facts.clean = git('status', '--porcelain').stdout.trim() === '';
    const remote = git('config', '--get', 'remote.origin.url');
    facts.remoteUrl = remote.code === 0 ? firstLine(remote.stdout) || null : null;
    const symbolic = git('symbolic-ref', '--short', 'refs/remotes/origin/HEAD');
    facts.defaultBranch = symbolic.code === 0 ? firstLine(symbolic.stdout).replace(/^origin\//, '') || null : null;
    if (!facts.defaultBranch && facts.remoteUrl) {
      const view = run(gh, ['repo', 'view', '--json', 'defaultBranchRef', '-q', '.defaultBranchRef.name']);
      facts.defaultBranch = view.code === 0 ? firstLine(view.stdout) || null : null;
    }
    facts.ghAuthed = run(gh, ['auth', 'status']).code === 0;
    facts.installing = existsSync(join(target, INSTALLING_MARKER));
    facts.branchTaken =
      git('show-ref', '--verify', '--quiet', `refs/heads/${branch}`).code === 0 ||
      (facts.remoteUrl ? git('ls-remote', '--exit-code', '--heads', 'origin', branch).code === 0 : false);
  }
  const problems = prPreflight(facts);
  if (problems.length) {
    const error = new CliError(`--pr preflight failed:\n${problems.map((p) => `  FAIL ${p.message}`).join('\n')}`);
    error.problems = problems;
    throw error;
  }
  const base = facts.defaultBranch;

  if (o.dryRun) {
    info(`Dry run: would branch ${branch} from origin/${base}, install, commit, push, and open a pull request`);
    return { ...runInstall(o, kit), branch, base, pr: null };
  }

  const original = firstLine(git('rev-parse', '--abbrev-ref', 'HEAD').stdout);
  must(git('fetch', '-q', 'origin', base), `git fetch origin ${base}`);
  must(git('checkout', '-q', '-b', branch, `origin/${base}`), `git checkout -b ${branch}`);
  let result;
  let committed = false;
  try {
    // The install sees the project as origin/<base> has it.
    result = runInstall(o, kit);
    must(git('add', '-A'), 'git add');
    if (git('diff', '--cached', '--quiet').code === 0) {
      throw new CliError(`origin/${base} already has asdd-harness-kit ${version} with nothing to change: no pull request`, 0);
    }
    const title = result.previous && result.previous !== version ? `chore: upgrade asdd-harness-kit to ${version}` : `chore: install asdd-harness-kit ${version}`;
    must(git('commit', '-q', '-m', title), 'git commit');
    committed = true;
    result.title = title;
  } catch (error) {
    // Nothing was committed: the tree was clean, so everything here came from this run.
    git('reset', '-q', '--hard');
    git('clean', '-fdq');
    git('checkout', '-q', original);
    git('branch', '-D', branch);
    if (error instanceof CliError && error.code === 0) {
      ok(error.message);
      return { ok: true, upToDate: true, branch: null, base, pr: null };
    }
    throw error;
  }

  try {
    const pushed = git('push', '-q', '-u', 'origin', branch);
    if (pushed.code !== 0) {
      throw new CliError(
        `git push origin ${branch} failed: ${firstLine(pushed.stderr) || `exit ${pushed.code}`}. The commit is on the local branch ${branch}: push it and open the pull request, or delete the branch and run again`,
      );
    }
    const pr = run(gh, ['pr', 'create', '--base', base, '--head', branch, '--title', result.title, '--body', prBody(result, base)]);
    if (pr.code !== 0) {
      throw new CliError(
        `gh pr create failed: ${firstLine(pr.stderr) || `exit ${pr.code}`}. The branch ${branch} is pushed: open the pull request with: gh pr create --base ${base} --head ${branch} --fill`,
      );
    }
    const url = pr.stdout.split('\n').map((l) => l.trim()).filter((l) => /^https?:\/\/\S+$/.test(l)).at(-1) ?? null;
    log('');
    ok(`Pull request: ${url ?? firstLine(pr.stdout)}`);
    log(`  Merge it, pull ${base}, then fill the bindings and run: asdd doctor`);
    return { ...result, branch, base, pr: url };
  } finally {
    if (committed) git('checkout', '-q', original);
  }
}
